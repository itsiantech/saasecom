const { getSummary, getSubreport, getTopCustomers } = require("./reportQuery");
const { REPORT_EXPORT_MAX_ROWS, REPORT_TIMEZONE, CUSTOMER_RANGES } = require("../lib/reportConstants");

const RANGE_LABELS = {
  monthly: "Monthly",
  half_yearly: "Half yearly",
  yearly: "Yearly",
};

function escapeHtml(value) {
  return String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function csvCell(value) {
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  let text = String(value == null ? "" : value);
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function generatedLabel(date, timezone) {
  return `${new Intl.DateTimeFormat("en-GB", {
    timeZone: timezone,
    year: "numeric",
    month: "short",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
  }).format(date)} (${timezone})`;
}

async function buildReportData(
  storeId,
  { report, period, sort = "", limit = 100, now = new Date(), timezone = REPORT_TIMEZONE },
  adminName = "Admin"
) {
  const titleMap = {
    summary: "Sales report",
    products: "Product-wise sales",
    categories: "Category-wise sales",
    coupons: "Coupon-wise sales",
    customers: "Top customers",
  };
  const title = titleMap[report];
  if (!title) throw Object.assign(new Error("Report pawa jayni"), { status: 400 });

  const meta = [
    ["Report", title],
    ["Period", `${period.from} – ${period.to}`],
    ["Timezone", timezone],
    ["Generated at", generatedLabel(now, timezone)],
    ["Generated by", adminName || "Admin"],
  ];
  if (report === "customers" && period.range) meta.splice(2, 0, ["Range", RANGE_LABELS[period.range] || period.range]);

  let headers = [];
  let rows = [];

  if (report === "summary") {
    const data = await getSummary(storeId, period, { now, timezone });
    headers = ["Metric", "Value", "Orders"];
    rows = [
      ["Sales in this period", data.sales, ""],
      ["Average daily sales", data.averageDailySales, ""],
      ["Net sales this year", data.netSalesThisYear, ""],
      ["Orders placed", data.ordersPlaced, ""],
      ["Items purchased", data.itemsPurchased, ""],
      ["Refunded orders", data.refundedOrders, ""],
      ["Charged for shipping", data.shippingCharged, ""],
      ["Worth of coupons used", data.couponsWorth, ""],
    ];
    rows.push([]);
    rows.push(["Chart", "", ""]);
    rows.push(["Bucket", "Sales", "Orders"]);
    for (const bucket of data.chart.buckets) rows.push([bucket.label, bucket.sales, bucket.orders]);
  } else if (report === "products" || report === "categories" || report === "coupons") {
    const data = await getSubreport(storeId, period, report, {
      now,
      timezone,
      sort,
      page: 1,
      limit: Math.min(REPORT_EXPORT_MAX_ROWS, Math.max(1, Number(limit) || REPORT_EXPORT_MAX_ROWS)),
      maxLimit: REPORT_EXPORT_MAX_ROWS,
    });
    if (report === "products") {
      headers = ["Product", "Sales (BDT)", "Quantity", "Orders"];
      rows = data.rows.map((row) => [row.name, row.sales, row.quantity, row.orders]);
    } else if (report === "categories") {
      headers = ["Category", "Sales (BDT)", "Quantity", "Orders"];
      rows = data.rows.map((row) => [row.name, row.sales, row.quantity, row.orders]);
    } else {
      headers = ["Coupon code", "Label", "Discount (BDT)", "Orders"];
      rows = data.rows.map((row) => [row.code, row.label, row.discount, row.orders]);
    }
  } else {
    if (!CUSTOMER_RANGES.includes(period.range)) {
      throw Object.assign(new Error("Customer range monthly, half_yearly ba yearly hote hobe"), { status: 400 });
    }
    const data = await getTopCustomers(storeId, period, {
      now,
      timezone,
      limit: Math.min(100, Math.max(1, Number(limit) || 100)),
    });
    headers = ["Customer", "Type", "Orders", "Total spent (BDT)"];
    rows = data.rows.map((row) => [row.name, row.isGuest ? "Guest" : "Registered", row.orders, row.totalSpent]);
  }

  return {
    report,
    title,
    meta,
    headers,
    rows,
    period,
    adminName: adminName || "Admin",
    generatedAt: now,
    timezone,
  };
}

function csvRows(data) {
  const rows = [];
  for (const [label, value] of data.meta) rows.push([label, value]);
  rows.push([]);
  rows.push(data.headers);
  for (const row of data.rows) rows.push(row);
  return rows;
}

function buildCsv(data) {
  return `\uFEFF${csvRows(data)
    .map((row) => row.map(csvCell).join(","))
    .join("\r\n")}`;
}

function csvFileName(data) {
  const base = data.report === "customers" ? "top-customers" : `sales-${data.report}`;
  return `${base}-${data.period.from}_${data.period.to}.csv`.replace(/[^a-zA-Z0-9_.-]/g, "-");
}

function cellHtml(value) {
  if (typeof value === "number" && Number.isFinite(value)) return escapeHtml(value);
  return escapeHtml(value);
}

function buildPrintHtml(data) {
  const metaRows = data.meta
    .map(
      ([label, value]) =>
        `<tr><th>${escapeHtml(label)}</th><td>${escapeHtml(value)}</td></tr>`
    )
    .join("");
  const heading = data.headers.map((header) => `<th>${escapeHtml(header)}</th>`).join("");
  const body = data.rows
    .map((row) => {
      if (!row.length) return '<tr class="spacer"><td colspan="' + data.headers.length + '"></td></tr>';
      return `<tr>${row.map((value) => `<td>${cellHtml(value)}</td>`).join("")}</tr>`;
    })
    .join("");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(data.title)} — ${escapeHtml(data.period.from)} to ${escapeHtml(data.period.to)}</title>
<style>
  :root { color-scheme: light; }
  * { box-sizing: border-box; }
  body { font-family: "Inter", "Hind Siliguri", system-ui, sans-serif; margin: 32px; color: #1f1c17; background: #fff; }
  h1 { font-size: 24px; margin: 0 0 4px; }
  .sub { color: #6b6255; font-size: 13px; margin-bottom: 20px; }
  table { width: 100%; border-collapse: collapse; font-size: 13px; }
  th, td { border: 1px solid #e5dfd4; padding: 8px 10px; text-align: left; vertical-align: top; }
  thead th { background: #f6f1e8; font-weight: 600; }
  tbody tr:nth-child(even) td { background: #fbf9f5; }
  .meta { width: auto; margin-bottom: 22px; }
  .meta th { background: transparent; width: 140px; }
  .meta td, .meta th { border: 0; padding: 3px 8px 3px 0; }
  .spacer td { border-left: 0; border-right: 0; height: 12px; background: #fff !important; }
  .toolbar { margin-bottom: 18px; }
  button { font: inherit; padding: 10px 16px; border: 1px solid #c9a961; background: #c9a961; color: #1b1710; border-radius: 8px; cursor: pointer; min-height: 44px; }
  footer { margin-top: 24px; font-size: 12px; color: #6b6255; }
  @media print { body { margin: 0; } .toolbar { display: none; } th, td { padding: 6px 8px; } }
</style>
</head>
<body>
  <div class="toolbar"><button type="button" onclick="window.print()">Print / Save as PDF</button></div>
  <h1>${escapeHtml(data.title)}</h1>
  <p class="sub">${escapeHtml(data.period.from)} – ${escapeHtml(data.period.to)} · generated ${escapeHtml(
    generatedLabel(data.generatedAt, data.timezone)
  )}</p>
  <table class="meta"><tbody>${metaRows}</tbody></table>
  <table>
    <thead><tr>${heading}</tr></thead>
    <tbody>${body}</tbody>
  </table>
  <footer>${escapeHtml(data.adminName)} · ${escapeHtml(data.timezone)}</footer>
</body>
</html>`;
}

module.exports = {
  buildReportData,
  buildCsv,
  csvRows,
  csvFileName,
  buildPrintHtml,
  csvCell,
  escapeHtml,
};
